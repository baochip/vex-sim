module SDFCND (
    input  wire SI,   // scan data input
    input  wire D,    // functional data input
    input  wire SE,   // scan enable (1 = select SI, 0 = select D)
    input  wire CP,   // clock, rising-edge triggered
    input  wire CDN,  // asynchronous clear, active low
    output reg  Q,
    output wire QN
);

    // scan mux (SE = 1 selects SI)
    wire d_mux = SE ? SI : D;

    always @(posedge CP or negedge CDN) begin
        if (!CDN)
            Q <= 1'b0;
        else
            Q <= d_mux;
    end

    assign QN = ~Q;

endmodule


