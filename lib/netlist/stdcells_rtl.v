module DFCSND (
    input  wire D,    // functional data input
    input  wire CP,   // clock, rising-edge triggered
    input  wire CDN,  // asynchronous clear, active low
    input  wire SDN,  // asynchronous set, active low
    output reg  Q,
    output wire QN
);

    // Clear has priority over set when both are asserted.
    // Sim note: if CDN is released while SDN is still low, the original
    // UDP model sets Q=1 immediately; this template holds Q=0 until the
    // next active clock edge. Synthesized hardware is unaffected.
    always @(posedge CP or negedge CDN or negedge SDN) begin
        if (!CDN)
            Q <= 1'b0;
        else if (!SDN)
            Q <= 1'b1;
        else
            Q <= D;
    end

    // QN is also forced low while SDN is asserted
    assign QN = ~Q & SDN;

endmodule


